/**
 * RFC 4013 SASLprep for PDF revision-6 passwords. Range tables below are
 * generated from Python stdlib stringprep (Unicode 3.2), RFC 3454 B.1, C.1.2,
 * C.2-C.9 and D.1/D.2. Unassigned code points are allowed, as for a query
 * string, so modern passwords (including emoji) remain usable.
 */
export function preparePdfPassword(password: string): string {
  if (typeof password !== "string") throw new TypeError("A PDF password must be a string.");
  let mapped = "";
  for (const character of password) {
    const point = character.codePointAt(0)!;
    // U+200B occurs in both tables. Mapping spaces first follows the PDF
    // reader convention, including pdf.js password handling.
    if (inRanges(NON_ASCII_SPACES, point)) mapped += " ";
    else if (!inRanges(MAPPED_TO_NOTHING, point)) mapped += character;
  }
  const prepared = mapped.normalize("NFKC");
  let first = -1, last = -1, hasRandAL = false, hasLeftToRight = false;
  for (const character of prepared) {
    const point = character.codePointAt(0)!;
    if (inRanges(PROHIBITED, point)) {
      throw new RangeError(`The PDF password contains a prohibited Unicode character (U+${point.toString(16).toUpperCase().padStart(4, "0")}).`);
    }
    if (first < 0) first = point;
    last = point;
    hasRandAL ||= inRanges(RANDAL, point);
    hasLeftToRight ||= inRanges(LEFT_TO_RIGHT, point);
  }
  if (hasRandAL && (hasLeftToRight || !inRanges(RANDAL, first) || !inRanges(RANDAL, last))) {
    throw new RangeError("The PDF password violates the SASLprep bidirectional text rules.");
  }
  return prepared;
}

function inRanges(ranges: readonly number[], point: number): boolean {
  let low = 0, high = ranges.length / 2 - 1;
  while (low <= high) {
    const middle = (low + high) >>> 1, start = ranges[middle * 2], end = ranges[middle * 2 + 1];
    if (point < start) high = middle - 1;
    else if (point > end) low = middle + 1;
    else return true;
  }
  return false;
}

