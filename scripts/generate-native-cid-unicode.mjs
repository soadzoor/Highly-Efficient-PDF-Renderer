async function locateSourceRoot(root) {
  const nested = join(root, "pdf2unicode");
  try {
    if ((await stat(nested)).isDirectory()) return nested;
  } catch {
    // The caller may have supplied pdf2unicode directly.
  }
  if ((await stat(root)).isDirectory() && basename(root) === "pdf2unicode") return root;
  throw new Error(`${root}: expected a mapping-resources-pdf checkout or its pdf2unicode directory.`);
}

async function verifySourceTree(root, names) {
  const hash = createHash("sha256");
  for (const name of names) {
    const bytes = await readFile(join(root, name));
    hash.update(Buffer.from(`${Buffer.byteLength(name)}:${name}:${bytes.byteLength}:`, "utf8"));
    hash.update(bytes);
  }
  const actual = hash.digest("hex");
  if (actual !== SOURCE_TREE_SHA256) {
    throw new Error(
      `Adobe mapping-resources source tree hash mismatch: expected ${SOURCE_TREE_SHA256}, received ${actual}.`
    );
  }
}

function parseMappingResource(source, path, expected) {
  const body = source.replace(/%[^\r\n]*/g, " ");
  const cmapName = requireSingleMatch(body, /\/CMapName\s+\/([^\s/<>{}\[\]()]+)\s+def\b/g, path, "CMapName");
  const registry = requireSingleMatch(body, /\/Registry\s+\(([^()]*)\)\s+def\b/g, path, "Registry");
  const sourceOrdering = requireSingleMatch(body, /\/Ordering\s+\(([^()]*)\)\s+def\b/g, path, "Ordering");
  const supplement = Number(requireSingleMatch(body, /\/Supplement\s+(\d+)\s+def\b/g, path, "Supplement"));
  const cmapVersion = requireSingleMatch(body, /\/CMapVersion\s+([0-9.]+)\s+def\b/g, path, "CMapVersion");
  if (
    cmapName !== expected.fileName || registry !== "Adobe" ||
    sourceOrdering !== expected.sourceOrdering || supplement !== expected.supplement ||
    cmapVersion !== expected.cmapVersion
  ) {
    throw new Error(`${path}: pinned CMap identity metadata does not match.`);
  }

  const mappings = new Map();
  let bfcharCount = 0;
  let bfrangeCount = 0;
  parseBlocks(body, "beginbfchar", "endbfchar", path, (line) => {
    const match = line.match(/^\s*<([0-9A-Fa-f]+)>\s+<([0-9A-Fa-f]+)>\s*$/);
    if (!match) throw new Error(`${path}: malformed bfchar entry: ${line.trim()}`);
    const cid = parseCid(match[1], path);
    setMapping(mappings, cid, decodeUtf16BeHex(match[2], path), path);
    bfcharCount += 1;
  });
  parseBlocks(body, "beginbfrange", "endbfrange", path, (line) => {
    const match = line.match(
      /^\s*<([0-9A-Fa-f]+)>\s+<([0-9A-Fa-f]+)>\s+<([0-9A-Fa-f]+)>\s*$/
    );
    if (!match) throw new Error(`${path}: malformed or unsupported bfrange entry: ${line.trim()}`);
    const start = parseCid(match[1], path);
    const end = parseCid(match[2], path);
    if (end < start) throw new Error(`${path}: reversed bfrange CID interval.`);
    const target = parseHexBytes(match[3], path, "bfrange target");
    for (let cid = start; cid <= end; cid += 1) {
      setMapping(
        mappings,
        cid,
        decodeUtf16Be(incrementBigEndian(target, cid - start, path), path),
        path
      );
    }
    bfrangeCount += 1;
  });
  const unsupported = [...body.matchAll(/\b(begin(?:bf|cid|notdef)[a-z]+)\b/g)]
    .map((match) => match[1])
    .filter((operator) => operator !== "beginbfchar" && operator !== "beginbfrange");
  if (unsupported.length > 0) {
    throw new Error(`${path}: unsupported mapping operators: ${[...new Set(unsupported)].join(", ")}.`);
  }
  const maxCid = Math.max(...mappings.keys());
  if (
    bfcharCount !== expected.bfcharCount || bfrangeCount !== expected.bfrangeCount ||
    mappings.size !== expected.mappingCount || maxCid !== expected.maxCid
  ) {
    throw new Error(`${path}: pinned mapping counts do not match.`);
  }
  return {
    collection: expected.collection,
    registry,
    supplement,
    cmapVersion,
    mappings,
    maxCid,
    bfcharCount,
    bfrangeCount
  };
}

function requireSingleMatch(source, expression, path, label) {
  const matches = [...source.matchAll(expression)];
  if (matches.length !== 1) throw new Error(`${path}: expected exactly one /${label}.`);
  return matches[0][1];
}

function parseBlocks(source, begin, end, path, consume) {
  const expression = new RegExp(`(\\d+)\\s+${begin}\\b([\\s\\S]*?)\\b${end}\\b`, "g");
  for (const match of source.matchAll(expression)) {
    const expected = Number(match[1]);
    const lines = match[2].split(/\r?\n/).filter((line) => line.trim().length > 0);
    if (lines.length !== expected) {
      throw new Error(`${path}: ${begin} declares ${expected} entries but contains ${lines.length}.`);
    }
    for (const line of lines) consume(line);
  }
}

function parseCid(hex, path) {
  if (hex.length !== 4) throw new Error(`${path}: CID source codes must contain exactly two bytes.`);
  const cid = Number.parseInt(hex, 16);
  if (!Number.isSafeInteger(cid) || cid < 0 || cid > MAX_CID) {
    throw new Error(`${path}: CID is outside the 16-bit CID space.`);
  }
  return cid;
}

function parseHexBytes(hex, path, label) {
  if (hex.length === 0 || (hex.length & 1) !== 0 || hex.length > 1024) {
    throw new Error(`${path}: ${label} must contain 1 through 512 bytes.`);
  }
  const bytes = new Uint8Array(hex.length / 2);
  for (let index = 0; index < bytes.length; index += 1) {
    const value = Number.parseInt(hex.slice(index * 2, index * 2 + 2), 16);
    if (!Number.isFinite(value)) throw new Error(`${path}: ${label} contains invalid hex.`);
    bytes[index] = value;
  }
  return bytes;
}

function decodeUtf16BeHex(hex, path) {
  return decodeUtf16Be(parseHexBytes(hex, path, "Unicode target"), path);
}

function decodeUtf16Be(bytes, path) {
  if ((bytes.length & 1) !== 0) throw new Error(`${path}: Unicode target has odd byte length.`);
  const units = [];
  for (let offset = 0; offset < bytes.length; offset += 2) {
    units.push((bytes[offset] << 8) | bytes[offset + 1]);
  }
  validateUtf16(units, path);
  return String.fromCharCode(...units);
}

function validateUtf16(units, path) {
  if (units.length === 0) throw new Error(`${path}: Unicode target is empty.`);
  for (let index = 0; index < units.length; index += 1) {
    const unit = units[index];
    if (unit >= 0xd800 && unit <= 0xdbff) {
      const low = units[++index];
      if (low === undefined || low < 0xdc00 || low > 0xdfff) {
        throw new Error(`${path}: Unicode target contains an unpaired high surrogate.`);
      }
    } else if (unit >= 0xdc00 && unit <= 0xdfff) {
      throw new Error(`${path}: Unicode target contains an unpaired low surrogate.`);
    }
  }
}

function incrementBigEndian(bytes, increment, path) {
  const result = bytes.slice();
  let carry = increment;
  for (let index = result.length - 1; index >= 0 && carry > 0; index -= 1) {
    const sum = result[index] + carry;
    result[index] = sum & 0xff;
    carry = Math.floor(sum / 256);
  }
  if (carry !== 0) throw new Error(`${path}: bfrange Unicode target overflows.`);
  return result;
}

function setMapping(mappings, cid, unicode, path) {
  if (mappings.has(cid)) throw new Error(`${path}: duplicate CID mapping for ${cid}.`);
  mappings.set(cid, unicode);
}

function encodeShard(definition) {
  const tokens = new Uint32Array(definition.maxCid + 1);
  const pool = [];
  const sequenceOffsets = new Map();
  let scalarMappingCount = 0;
  let sequenceMappingCount = 0;
  for (const [cid, unicode] of definition.mappings) {
    const scalars = [...unicode];
    if (scalars.length === 1) {
      tokens[cid] = scalars[0].codePointAt(0) + 1;
      scalarMappingCount += 1;
      continue;
    }
    let offset = sequenceOffsets.get(unicode);
    if (offset === undefined) {
      offset = pool.length;
      if (offset >= SEQUENCE_TOKEN) throw new Error("HCU1 Unicode string pool exceeds 31-bit offsets.");
      const units = Array.from(unicode, (character) => character).flatMap((character) => {
        const codePoint = character.codePointAt(0);
        if (codePoint <= 0xffff) return [codePoint];
        const adjusted = codePoint - 0x1_0000;
        return [0xd800 + (adjusted >>> 10), 0xdc00 + (adjusted & 0x3ff)];
      });
      writeVarUint(pool, units.length);
      for (const unit of units) {
        pool.push(unit >>> 8, unit & 0xff);
      }
      sequenceOffsets.set(unicode, offset);
    }
    tokens[cid] = (SEQUENCE_TOKEN | offset) >>> 0;
    sequenceMappingCount += 1;
  }

  const output = [...MAGIC];
  writeAscii(output, definition.registry);
  writeAscii(output, definition.collection);
  writeVarUint(output, definition.supplement);
  writeVarUint(output, definition.maxCid);
  writeVarUint(output, definition.mappings.size);
  writeVarUint(output, tokens.byteLength);
  for (const token of tokens) writeUint32(output, token);
  writeVarUint(output, pool.length);
  output.push(...pool);
  return {
    bytes: Buffer.from(output),
    scalarMappingCount,
    sequenceMappingCount,
    sequenceCount: sequenceOffsets.size,
    stringPoolByteLength: pool.length
  };
}

function writeAscii(output, value) {
  const bytes = Buffer.from(value, "ascii");
  if (bytes.length === 0 || bytes.length > 127 || bytes.toString("ascii") !== value) {
    throw new Error(`HCU1 identity ${value} is not bounded printable ASCII.`);
  }
  writeVarUint(output, bytes.length);
  output.push(...bytes);
}

function writeVarUint(output, value) {
  if (!Number.isSafeInteger(value) || value < 0 || value > 0xffff_ffff) {
    throw new RangeError(`Cannot encode unsigned integer ${value}.`);
  }
  let remaining = value >>> 0;
  do {
    const byte = remaining & 0x7f;
    remaining >>>= 7;
    output.push(byte | (remaining === 0 ? 0 : 0x80));
  } while (remaining !== 0);
}

function writeUint32(output, value) {
  output.push(value >>> 24, value >>> 16 & 0xff, value >>> 8 & 0xff, value & 0xff);
}

function sha256(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

function createRegistry(metadata) {
  const collections = metadata.map(({ collection }) => collection);
  const compactMetadata = Object.fromEntries(metadata.map((entry) => [entry.collection, {
    registry: entry.registry,
    ordering: entry.ordering,
    supplement: entry.supplement,
    maxCid: entry.maxCid,
    mappingCount: entry.mappingCount,
    shardByteLength: entry.shardByteLength
  }]));
  const compactMetadataSource = Object.entries(compactMetadata)
    .map(([collection, value]) =>
      `${JSON.stringify(collection)}:Object.freeze(${JSON.stringify(value)})`
    )
    .join(",");
  const cases = metadata.map(({ collection }) =>
    `    case ${JSON.stringify(collection)}: return (await import(${JSON.stringify(`./${collection}`)})).default;`
  ).join("\n");
  return `// Generated by scripts/generate-native-cid-unicode.mjs. Do not edit.\n` +
    `export const NATIVE_CID_TO_UNICODE_SOURCE_COMMIT = ${JSON.stringify(SOURCE_COMMIT)};\n` +
    `export const NATIVE_CID_TO_UNICODE_SOURCE_TREE_SHA256 = ${JSON.stringify(SOURCE_TREE_SHA256)};\n` +
    `export const NATIVE_CID_TO_UNICODE_COLLECTIONS = Object.freeze(${JSON.stringify(collections)} as const);\n` +
    `export type NativeCidToUnicodeCollection = (typeof NATIVE_CID_TO_UNICODE_COLLECTIONS)[number];\n` +
    `export const NATIVE_CID_TO_UNICODE_METADATA = Object.freeze({${compactMetadataSource}} as const);\n` +
    `const NATIVE_CID_TO_UNICODE_COLLECTION_SET: ReadonlySet<string> = new Set(NATIVE_CID_TO_UNICODE_COLLECTIONS);\n` +
    `export function isNativeCidToUnicodeCollection(value: string): value is NativeCidToUnicodeCollection {\n` +
    `  return NATIVE_CID_TO_UNICODE_COLLECTION_SET.has(value);\n` +
    `}\n` +
    `export async function importNativeCidToUnicodeShard(collection: NativeCidToUnicodeCollection): Promise<string> {\n` +
    `  switch (collection) {\n${cases}\n` +
    `  }\n` +
    `}\n`;
}
