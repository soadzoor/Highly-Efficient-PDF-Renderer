import { createHash } from "node:crypto";
import { readdir, readFile, stat, writeFile, mkdir } from "node:fs/promises";
import { basename, dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE_TAG = "20231115";
const SOURCE_ARCHIVE_SHA256 = "a88c3beee8d2f139b47f9d7e932ec198be24991dd46fcaef2961b4b5ea855ea2";
const SOURCE_TREE_SHA256 = "94d706b3864e4d596a81389e9edbab69b42cd969a872ee5b74c7ee49b7148f76";
const MAGIC = Uint8Array.of(0x48, 0x43, 0x4d, 0x33); // HCM3
const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = resolve(scriptDirectory, "..");
const sourceRoot = process.argv[2] ? resolve(process.argv[2]) : null;
const generatedRoot = resolve(repositoryRoot, "src/pdf/cmaps/generated");

if (!sourceRoot) {
  throw new Error(
    "Usage: node scripts/generate-native-cmaps.mjs /path/to/cmap-resources-20231115"
  );
}

const sourceFiles = (await walk(sourceRoot))
  .filter((path) => relative(sourceRoot, path).replaceAll("\\", "/").includes("/CMap/"))
  .sort((left, right) =>
    relative(sourceRoot, left).localeCompare(relative(sourceRoot, right))
  );

if (sourceFiles.length !== 202) {
  throw new Error(`Expected 202 Adobe CMap resources, found ${sourceFiles.length}.`);
}
await verifySourceTree(sourceFiles);

const parsed = [];
const names = new Set();
for (const path of sourceFiles) {
  const bytes = await readFile(path);
  const definition = parseAdobeCMap(bytes.toString("latin1"), path);
  if (names.has(definition.name)) {
    throw new Error(`Duplicate CMap resource name /${definition.name}.`);
  }
  names.add(definition.name);
  parsed.push({
    ...definition,
    sourcePath: relative(sourceRoot, path).replaceAll("\\", "/"),
    sourceByteLength: bytes.byteLength,
    sourceSha256: sha256(bytes)
  });
}

for (const definition of parsed) {
  if (definition.baseName && !names.has(definition.baseName)) {
    throw new Error(`/${definition.name} uses missing base CMap /${definition.baseName}.`);
  }
}
validateInheritance(parsed);

await mkdir(generatedRoot, { recursive: true });
const metadata = [];
for (const definition of parsed) {
  const binary = encodeShard(definition);
  const fileName = `${definition.name}.ts`;
  const moduleSource = [
    "// Generated by scripts/generate-native-cmaps.mjs. Do not edit.",
    `const shard: string = "${binary.toString("base64")}";`,
    "export default shard;",
    ""
  ].join("\n");
  await writeFile(join(generatedRoot, fileName), moduleSource, "utf8");
  metadata.push({
    name: definition.name,
    sourcePath: definition.sourcePath,
    sourceByteLength: definition.sourceByteLength,
    sourceSha256: definition.sourceSha256,
    shardByteLength: binary.byteLength,
    shardSha256: sha256(binary),
    mappingCount: countMappings(definition.ranges),
    rangeCount: definition.ranges.length,
    notdefMappingCount: countMappings(definition.notdefRanges),
    notdefRangeCount: definition.notdefRanges.length,
    codeSpaceCount: definition.codeSpaces.length,
    baseName: definition.baseName,
    writingMode: definition.writingMode,
    registry: definition.systemInfo.registry,
    ordering: definition.systemInfo.ordering,
    supplement: definition.systemInfo.supplement
  });
}

await writeFile(join(generatedRoot, "registry.ts"), createRegistry(metadata), "utf8");
await writeFile(join(generatedRoot, "manifest.json"), `${JSON.stringify({
    format: "HEPR-CMap-3",
  source: "adobe-type-tools/cmap-resources",
  sourceTag: SOURCE_TAG,
  sourceArchiveSha256: SOURCE_ARCHIVE_SHA256,
  sourceTreeSha256: SOURCE_TREE_SHA256,
  resources: metadata
}, null, 2)}\n`, "utf8");

const sourceBytes = metadata.reduce((sum, entry) => sum + entry.sourceByteLength, 0);
const shardBytes = metadata.reduce((sum, entry) => sum + entry.shardByteLength, 0);
console.log(
  `generated ${metadata.length} HEPR CMap shards: ${sourceBytes} source bytes -> ${shardBytes} binary bytes`
);

async function walk(root) {
  const entries = await readdir(root, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const path = join(root, entry.name);
    if (entry.isDirectory()) files.push(...await walk(path));
    else if (entry.isFile() && (await stat(path)).isFile()) files.push(path);
  }
  return files;
}

async function verifySourceTree(paths) {
  const hash = createHash("sha256");
  for (const path of paths) {
    const sourcePath = relative(sourceRoot, path).replaceAll("\\", "/");
    const bytes = await readFile(path);
    hash.update(Buffer.from(`${Buffer.byteLength(sourcePath)}:${sourcePath}:${bytes.byteLength}:`, "utf8"));
    hash.update(bytes);
  }
  const actual = hash.digest("hex");
  if (actual !== SOURCE_TREE_SHA256) {
    throw new Error(
      `Adobe CMap source tree hash mismatch: expected ${SOURCE_TREE_SHA256}, received ${actual}.`
    );
  }
}

function parseAdobeCMap(source, path) {
  const body = source.replace(/%[^\r\n]*/g, " ");
  const nameMatch = body.match(/\/CMapName\s+\/([^\s/<>\[\](){}%]+)\s+def\b/);
  if (!nameMatch) throw new Error(`${path}: missing /CMapName.`);
  const writingModeMatch = body.match(/\/WMode\s+([01])\s+def\b/);
  if (!writingModeMatch) throw new Error(`${path}: missing /WMode.`);
  const registryMatches = [...body.matchAll(/\/Registry\s+\(([^()]*)\)\s+def\b/g)];
  const orderingMatches = [...body.matchAll(/\/Ordering\s+\(([^()]*)\)\s+def\b/g)];
  const supplementMatches = [...body.matchAll(/\/Supplement\s+(\d+)\s+def\b/g)];
  if (
    registryMatches.length !== 1 || orderingMatches.length !== 1 ||
    supplementMatches.length !== 1
  ) {
    throw new Error(`${path}: expected exactly one complete /CIDSystemInfo dictionary.`);
  }
  const registry = registryMatches[0][1];
  const ordering = orderingMatches[0][1];
  const supplement = Number(supplementMatches[0][1]);
  if (
    registry !== "Adobe" || !/^[A-Za-z0-9_.-]{1,127}$/.test(ordering) ||
    !Number.isSafeInteger(supplement) || supplement < 0 || supplement > 0xffff
  ) {
    throw new Error(`${path}: invalid /CIDSystemInfo values.`);
  }
  const bases = [...body.matchAll(/\/([^\s/<>\[\](){}%]+)\s+usecmap\b/g)].map((match) => match[1]);
  if (bases.length > 1) throw new Error(`${path}: multiple usecmap bases.`);

  const codeSpaces = [];
  parseBlocks(body, "begincodespacerange", "endcodespacerange", path, (line) => {
    const match = line.match(/^\s*<([0-9A-Fa-f]+)>\s*<([0-9A-Fa-f]+)>\s*$/);
    if (!match) throw new Error(`${path}: malformed codespace entry: ${line.trim()}`);
    const start = parseHexCode(match[1], path);
    const end = parseHexCode(match[2], path);
    if (start.byteLength !== end.byteLength || end.code < start.code) {
      throw new Error(`${path}: invalid codespace interval.`);
    }
    codeSpaces.push({ byteLength: start.byteLength, start: start.code, end: end.code });
  });

  const ranges = [];
  parseBlocks(body, "begincidchar", "endcidchar", path, (line) => {
    const match = line.match(/^\s*<([0-9A-Fa-f]+)>\s+(\d+)\s*$/);
    if (!match) throw new Error(`${path}: malformed cidchar entry: ${line.trim()}`);
    const sourceCode = parseHexCode(match[1], path);
    const cid = Number(match[2]);
    validateCid(cid, path);
    ranges.push({
      byteLength: sourceCode.byteLength,
      start: sourceCode.code,
      end: sourceCode.code,
      firstCid: cid
    });
  });
  parseBlocks(body, "begincidrange", "endcidrange", path, (line) => {
    const match = line.match(/^\s*<([0-9A-Fa-f]+)>\s*<([0-9A-Fa-f]+)>\s+(\d+)\s*$/);
    if (!match) throw new Error(`${path}: malformed cidrange entry: ${line.trim()}`);
    const start = parseHexCode(match[1], path);
    const end = parseHexCode(match[2], path);
    const cid = Number(match[3]);
    validateCid(cid, path);
    if (start.byteLength !== end.byteLength || end.code < start.code) {
      throw new Error(`${path}: invalid CID interval.`);
    }
    if (cid + end.code - start.code > 0xffff) {
      throw new Error(`${path}: CID interval exceeds 65535.`);
    }
    ranges.push({
      byteLength: start.byteLength,
      start: start.code,
      end: end.code,
      firstCid: cid
    });
  });

  const notdefRanges = [];
  parseBlocks(body, "beginnotdefchar", "endnotdefchar", path, (line) => {
    const match = line.match(/^\s*<([0-9A-Fa-f]+)>\s+(\d+)\s*$/);
    if (!match) throw new Error(`${path}: malformed notdefchar entry: ${line.trim()}`);
    const sourceCode = parseHexCode(match[1], path);
    const cid = Number(match[2]);
    validateCid(cid, path);
    notdefRanges.push({
      byteLength: sourceCode.byteLength,
      start: sourceCode.code,
      end: sourceCode.code,
      firstCid: cid
    });
  });
  parseBlocks(body, "beginnotdefrange", "endnotdefrange", path, (line) => {
    const match = line.match(/^\s*<([0-9A-Fa-f]+)>\s*<([0-9A-Fa-f]+)>\s+(\d+)\s*$/);
    if (!match) throw new Error(`${path}: malformed notdefrange entry: ${line.trim()}`);
    const start = parseHexCode(match[1], path);
    const end = parseHexCode(match[2], path);
    const cid = Number(match[3]);
    validateCid(cid, path);
    if (start.byteLength !== end.byteLength || end.code < start.code) {
      throw new Error(`${path}: invalid notdef interval.`);
    }
    notdefRanges.push({
      byteLength: start.byteLength,
      start: start.code,
      end: end.code,
      firstCid: cid
    });
  });

  const unsupported = [...body.matchAll(/\b(begin(?:bf|notdef)[a-z]+)\b/g)]
    .map((match) => match[1])
    .filter((operator) => operator !== "beginnotdefchar" && operator !== "beginnotdefrange");
  if (unsupported.length > 0) {
    throw new Error(`${path}: unsupported mapping operators: ${[...new Set(unsupported)].join(", ")}.`);
  }

  const sortedCodeSpaces = codeSpaces.sort(compareIntervals);
  validateNonOverlapping(sortedCodeSpaces, path, "codespace");
  const sortedRanges = ranges.sort(compareIntervals);
  validateNonOverlapping(sortedRanges, path, "CID mapping");
  const sortedNotdefRanges = notdefRanges.sort(compareIntervals);
  validateNonOverlapping(sortedNotdefRanges, path, "notdef mapping");
  return {
    name: nameMatch[1],
    writingMode: Number(writingModeMatch[1]),
    baseName: bases[0] ?? null,
    systemInfo: { registry, ordering, supplement },
    codeSpaces: sortedCodeSpaces,
    ranges: mergeSequentialRanges(sortedRanges),
    notdefRanges: mergeConstantRanges(sortedNotdefRanges)
  };
}

function parseBlocks(source, begin, end, path, consume) {
  const expression = new RegExp(`(\\d+)\\s+${begin}\\b([\\s\\S]*?)\\b${end}\\b`, "g");
  for (const match of source.matchAll(expression)) {
    const expected = Number(match[1]);
    const lines = match[2].split(/\r?\n/).filter((line) => line.trim().length > 0);
    if (lines.length !== expected) {
      throw new Error(`${path}: ${begin} declares ${expected} entries but contains ${lines.length}.`);
    }
    for (const line of lines) consume(line);
  }
}

function parseHexCode(hex, path) {
  if (hex.length === 0 || hex.length > 8 || (hex.length & 1) !== 0) {
    throw new Error(`${path}: CMap source code must contain one through four bytes.`);
  }
  return { byteLength: hex.length / 2, code: Number.parseInt(hex, 16) >>> 0 };
}

function validateCid(value, path) {
  if (!Number.isSafeInteger(value) || value < 0 || value > 0xffff) {
    throw new Error(`${path}: CID ${value} is outside the 16-bit CID space.`);
  }
}

function compareIntervals(left, right) {
  return left.byteLength - right.byteLength || left.start - right.start || left.end - right.end;
}

function validateNonOverlapping(values, path, label) {
  let previous = null;
  for (const value of values) {
    if (previous && previous.byteLength === value.byteLength && previous.end >= value.start) {
      throw new Error(`${path}: overlapping ${label} intervals.`);
    }
    previous = value;
  }
}

function mergeSequentialRanges(values) {
  const result = [];
  for (const value of values) {
    const previous = result.at(-1);
    if (
      previous &&
      previous.byteLength === value.byteLength &&
      previous.end + 1 === value.start &&
      previous.firstCid + previous.end - previous.start + 1 === value.firstCid
    ) {
      previous.end = value.end;
    } else {
      result.push({ ...value });
    }
  }
  return result;
}

function mergeConstantRanges(values) {
  const result = [];
  for (const value of values) {
    const previous = result.at(-1);
    if (
      previous &&
      previous.byteLength === value.byteLength &&
      previous.end + 1 === value.start &&
      previous.firstCid === value.firstCid
    ) {
      previous.end = value.end;
    } else {
      result.push({ ...value });
    }
  }
  return result;
}

function validateInheritance(definitions) {
  const byName = new Map(definitions.map((definition) => [definition.name, definition]));
  for (const definition of definitions) {
    const seen = new Set([definition.name]);
    let current = definition;
    while (current.baseName) {
      if (seen.has(current.baseName)) {
        throw new Error(`CMap inheritance cycle through /${current.baseName}.`);
      }
      seen.add(current.baseName);
      current = byName.get(current.baseName);
      if (!current) throw new Error(`Missing CMap /${current.baseName}.`);
    }
  }
}

function encodeShard(definition) {
  const output = [...MAGIC, definition.writingMode];
  const base = Buffer.from(definition.baseName ?? "", "utf8");
  writeVarUint(output, base.byteLength);
  output.push(...base);
  writeVarUint(output, definition.codeSpaces.length);
  for (const range of definition.codeSpaces) {
    output.push(range.byteLength);
    writeVarUint(output, range.start);
    writeVarUint(output, range.end - range.start);
  }
  for (let byteLength = 1; byteLength <= 4; byteLength += 1) {
    const ranges = definition.ranges.filter((range) => range.byteLength === byteLength);
    writeVarUint(output, ranges.length);
    let previousEnd = -1;
    for (const range of ranges) {
      writeVarUint(output, range.start - previousEnd - 1);
      writeVarUint(output, range.end - range.start);
      writeVarUint(output, range.firstCid);
      previousEnd = range.end;
    }
  }
  for (let byteLength = 1; byteLength <= 4; byteLength += 1) {
    const ranges = definition.notdefRanges.filter((range) => range.byteLength === byteLength);
    writeVarUint(output, ranges.length);
    let previousEnd = -1;
    for (const range of ranges) {
      writeVarUint(output, range.start - previousEnd - 1);
      writeVarUint(output, range.end - range.start);
      writeVarUint(output, range.firstCid);
      previousEnd = range.end;
    }
  }
  return Buffer.from(output);
}

function writeVarUint(output, value) {
  if (!Number.isSafeInteger(value) || value < 0 || value > 0xffff_ffff) {
    throw new RangeError(`Cannot encode unsigned integer ${value}.`);
  }
  let remaining = value >>> 0;
  do {
    const byte = remaining & 0x7f;
    remaining >>>= 7;
    output.push(byte | (remaining === 0 ? 0 : 0x80));
  } while (remaining !== 0);
}

function countMappings(ranges) {
  return ranges.reduce((sum, range) => sum + range.end - range.start + 1, 0);
}

function sha256(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

function createRegistry(metadata) {
  const names = metadata.map(({ name }) => name);
  const systemInfos = [];
  const systemInfoIndexes = [];
  const systemInfoIndexByKey = new Map();
  for (const { registry, ordering, supplement } of metadata) {
    const key = `${registry}\u0000${ordering}\u0000${supplement}`;
    let index = systemInfoIndexByKey.get(key);
    if (index === undefined) {
      index = systemInfos.length;
      systemInfoIndexByKey.set(key, index);
      systemInfos.push({ registry, ordering, supplement });
    }
    systemInfoIndexes.push(index);
  }
  const cases = metadata.map(({ name }) =>
    `    case ${JSON.stringify(name)}: return (await import(${JSON.stringify(`./${name}`)})).default;`
  ).join("\n");
  return `// Generated by scripts/generate-native-cmaps.mjs. Do not edit.\n` +
    `export const NATIVE_CMAP_SOURCE_TAG = ${JSON.stringify(SOURCE_TAG)};\n` +
    `export const NATIVE_CMAP_SOURCE_ARCHIVE_SHA256 = ${JSON.stringify(SOURCE_ARCHIVE_SHA256)};\n` +
    `export const NATIVE_CMAP_SOURCE_TREE_SHA256 = ${JSON.stringify(SOURCE_TREE_SHA256)};\n` +
    `export const NATIVE_PREDEFINED_CMAP_NAMES = Object.freeze(${JSON.stringify(names)} as const);\n` +
    `export type NativePredefinedCMapName = (typeof NATIVE_PREDEFINED_CMAP_NAMES)[number];\n` +
    `export interface NativePredefinedCMapSystemInfo { readonly registry: string; readonly ordering: string; readonly supplement: number; }\n` +
    `const NATIVE_PREDEFINED_CMAP_SYSTEM_INFOS = Object.freeze(${JSON.stringify(systemInfos)}.map((value) => Object.freeze(value)));\n` +
    `const NATIVE_PREDEFINED_CMAP_SYSTEM_INFO_INDEXES = Uint8Array.of(${systemInfoIndexes.join(",")});\n` +
    `const NATIVE_PREDEFINED_CMAP_NAME_INDEX: ReadonlyMap<string, number> = new Map(NATIVE_PREDEFINED_CMAP_NAMES.map((name, index) => [name, index]));\n` +
    `export function isNativePredefinedCMapName(name: string): name is NativePredefinedCMapName {\n` +
    `  return NATIVE_PREDEFINED_CMAP_NAME_INDEX.has(name);\n` +
    `}\n` +
    `export function nativePredefinedCMapSystemInfo(name: NativePredefinedCMapName): Readonly<NativePredefinedCMapSystemInfo> {\n` +
    `  const nameIndex = NATIVE_PREDEFINED_CMAP_NAME_INDEX.get(name);\n` +
    `  if (nameIndex === undefined) throw new RangeError(\`Unknown predefined CMap /\${name}.\`);\n` +
    `  return NATIVE_PREDEFINED_CMAP_SYSTEM_INFOS[NATIVE_PREDEFINED_CMAP_SYSTEM_INFO_INDEXES[nameIndex]];\n` +
    `}\n` +
    `export async function importNativePredefinedCMapShard(name: NativePredefinedCMapName): Promise<string> {\n` +
    `  switch (name) {\n${cases}\n` +
    `  }\n` +
    `}\n`;
}
